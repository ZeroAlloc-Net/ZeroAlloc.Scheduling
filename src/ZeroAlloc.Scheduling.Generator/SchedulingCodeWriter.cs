using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using System.Globalization;
using System.Text;

namespace ZeroAlloc.Scheduling.Generator;

internal static class SchedulingCodeWriter
{
    public static void Write(SourceProductionContext ctx, JobModel model)
    {
        var sb = new StringBuilder();
        var typeFqn = $"global::{model.TypeFqn}";
        var executorName = JobNames.Executor(model.TypeName);
        var diMethodName = JobNames.RegistrationMethod(model.TypeName);
        var startupName = JobNames.RecurringStartup(model.TypeName);

        AppendHeader(sb, model.Namespace);

        if (model.IsStateless)
            AppendStatelessExecutor(sb, executorName, typeFqn, model.TypeFqn, model.MaxAttempts);
        else if (!model.IsMediatorBridge)
            AppendExecutor(sb, executorName, typeFqn, model.TypeFqn, model.MaxAttempts);

        if (model.IsRecurring)
            AppendRecurringStartup(sb, model, startupName, typeFqn);

        AppendDiExtension(sb, diMethodName, executorName, typeFqn, startupName,
                          model.IsRecurring, model.IsMediatorBridge, model.IsPublic);

        ctx.AddSource(model.HintName, SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static void AppendHeader(StringBuilder sb, string? ns)
    {
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection.Extensions;");
        sb.AppendLine("using Microsoft.Extensions.Hosting;");
        sb.AppendLine("using Microsoft.Extensions.Options;");
        sb.AppendLine("using ZeroAlloc.Scheduling;");
        sb.AppendLine();

        if (ns != null)
        {
            sb.AppendLine($"namespace {ns};");
            sb.AppendLine();
        }
    }

    private static void AppendExecutor(StringBuilder sb, string executorName, string typeFqn, string jobFqn, int maxAttempts)
    {
        sb.AppendLine($"internal sealed class {executorName} : global::ZeroAlloc.Scheduling.IJobTypeExecutor");
        sb.AppendLine("{");
        sb.AppendLine("    private readonly global::ZeroAlloc.Scheduling.IJobSerializer _serializer;");
        sb.AppendLine($"    public {executorName}(global::ZeroAlloc.Scheduling.IJobSerializer serializer) => _serializer = serializer;");
        sb.AppendLine($"    public string TypeName => \"{jobFqn}\";");
        sb.AppendLine($"    public int MaxAttempts => {maxAttempts.ToString(CultureInfo.InvariantCulture)};");
        sb.AppendLine("    public async global::System.Threading.Tasks.ValueTask ExecuteAsync(");
        sb.AppendLine("        byte[] payload,");
        sb.AppendLine("        global::ZeroAlloc.Scheduling.JobContext ctx,");
        sb.AppendLine("        global::System.Threading.CancellationToken ct)");
        sb.AppendLine("    {");
        sb.AppendLine($"        var job = _serializer.Deserialize<{typeFqn}>(payload);");
        sb.AppendLine("        await job.ExecuteAsync(ctx, ct).ConfigureAwait(false);");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    // A job without instance fields carries no state, so the payload is not read and the job
    // serializer is not needed. The first instance that constructs successfully is reused for
    // every later run. It is not a static initializer: a constructor that throws must fail only
    // that attempt, so a retry can construct the job again.
    private static void AppendStatelessExecutor(StringBuilder sb, string executorName, string typeFqn, string jobFqn, int maxAttempts)
    {
        sb.AppendLine($"internal sealed class {executorName} : global::ZeroAlloc.Scheduling.IJobTypeExecutor");
        sb.AppendLine("{");
        sb.AppendLine($"    private static {typeFqn}? s_job;");
        sb.AppendLine($"    public string TypeName => \"{jobFqn}\";");
        sb.AppendLine($"    public int MaxAttempts => {maxAttempts.ToString(CultureInfo.InvariantCulture)};");
        sb.AppendLine("    public global::System.Threading.Tasks.ValueTask ExecuteAsync(");
        sb.AppendLine("        byte[] payload,");
        sb.AppendLine("        global::ZeroAlloc.Scheduling.JobContext ctx,");
        sb.AppendLine("        global::System.Threading.CancellationToken ct)");
        sb.AppendLine($"        => (s_job ??= new {typeFqn}()).ExecuteAsync(ctx, ct);");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void AppendRecurringStartup(StringBuilder sb, JobModel model, string startupName, string typeFqn)
    {
        var cronLiteral = model.CronExpression != null
            ? $"\"{model.CronExpression}\""
            : $"global::ZeroAlloc.Scheduling.EveryToCron.Convert(global::ZeroAlloc.Scheduling.{model.EveryValue})";

        var maxAttemptsExpr = model.MaxAttempts > 0
            ? model.MaxAttempts.ToString(CultureInfo.InvariantCulture)
            : "_options.Value.DefaultMaxAttempts";

        sb.AppendLine($"internal sealed class {startupName} : global::Microsoft.Extensions.Hosting.IHostedService");
        sb.AppendLine("{");
        // The hosted service is a singleton and most stores are scoped, so the store is resolved
        // in a scope of its own for the seed rather than taken in the constructor.
        sb.AppendLine("    private readonly global::Microsoft.Extensions.DependencyInjection.IServiceScopeFactory _scopeFactory;");
        if (model.IsStateless)
        {
            // Nothing to serialize: the run is seeded with an empty payload, which the stateless
            // executor never reads, so no IJobSerializer has to be registered for this job.
            sb.AppendLine("    private readonly global::Microsoft.Extensions.Options.IOptions<global::ZeroAlloc.Scheduling.SchedulingOptions> _options;");
            sb.AppendLine($"    public {startupName}(global::Microsoft.Extensions.DependencyInjection.IServiceScopeFactory scopeFactory, global::Microsoft.Extensions.Options.IOptions<global::ZeroAlloc.Scheduling.SchedulingOptions> options)");
            sb.AppendLine("    { _scopeFactory = scopeFactory; _options = options; }");
        }
        else
        {
            sb.AppendLine("    private readonly global::ZeroAlloc.Scheduling.IJobSerializer _serializer;");
            sb.AppendLine("    private readonly global::Microsoft.Extensions.Options.IOptions<global::ZeroAlloc.Scheduling.SchedulingOptions> _options;");
            sb.AppendLine($"    public {startupName}(global::Microsoft.Extensions.DependencyInjection.IServiceScopeFactory scopeFactory, global::ZeroAlloc.Scheduling.IJobSerializer serializer, global::Microsoft.Extensions.Options.IOptions<global::ZeroAlloc.Scheduling.SchedulingOptions> options)");
            sb.AppendLine("    { _scopeFactory = scopeFactory; _serializer = serializer; _options = options; }");
        }
        var payloadExpr = model.IsStateless
            ? "global::System.Array.Empty<byte>()"
            : $"_serializer.Serialize(new {typeFqn}())";
        AppendStartAsyncBody(sb, model.TypeFqn, payloadExpr, cronLiteral, maxAttemptsExpr);
        sb.AppendLine("    public global::System.Threading.Tasks.Task StopAsync(global::System.Threading.CancellationToken ct) => global::System.Threading.Tasks.Task.CompletedTask;");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void AppendStartAsyncBody(StringBuilder sb, string jobFqn, string payloadExpr, string cronLiteral, string maxAttemptsExpr)
    {
        sb.AppendLine("    public async global::System.Threading.Tasks.Task StartAsync(global::System.Threading.CancellationToken ct)");
        sb.AppendLine("    {");
        sb.AppendLine($"        var cron = {cronLiteral};");
        sb.AppendLine("        var expr = global::Cronos.CronExpression.Parse(cron, global::Cronos.CronFormat.Standard);");
        sb.AppendLine("        var next = expr.GetNextOccurrence(global::System.DateTimeOffset.UtcNow, global::System.TimeZoneInfo.Utc);");
        sb.AppendLine("        if (next is null) return;");
        sb.AppendLine($"        var maxAttempts = {maxAttemptsExpr};");
        sb.AppendLine($"        var payload = {payloadExpr};");
        sb.AppendLine("        var scope = _scopeFactory.CreateAsyncScope();");
        sb.AppendLine("        try");
        sb.AppendLine("        {");
        sb.AppendLine("            var store = global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<global::ZeroAlloc.Scheduling.IJobStore>(scope.ServiceProvider);");
        sb.AppendLine($"            await store.UpsertRecurringAsync(\"{jobFqn}\", payload, next.Value, cron, maxAttempts, ct).ConfigureAwait(false);");
        sb.AppendLine("        }");
        sb.AppendLine("        finally");
        sb.AppendLine("        {");
        sb.AppendLine("            await scope.DisposeAsync().ConfigureAwait(false);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

    private static void AppendDiExtension(StringBuilder sb, string diMethodName, string executorName,
        string typeFqn, string startupName, bool isRecurring, bool isMediatorBridge, bool isPublic)
    {
        // The registration has the job's accessibility, so an internal job adds no public member to
        // its assembly. Internal jobs get a class of their own: the partial parts of one class
        // cannot differ in accessibility, and a namespace may hold public and internal jobs.
        // The members carry XML docs: a library that generates its documentation file with
        // warnings as errors would otherwise fail on CS1591.
        sb.AppendLine("/// <summary>Registers the <c>[Job]</c> types of this namespace with ZeroAlloc.Scheduling. Generated.</summary>");
        sb.AppendLine(isPublic
            ? "public static partial class SchedulingServiceCollectionExtensions"
            : "internal static partial class InternalSchedulingServiceCollectionExtensions");
        sb.AppendLine("{");
        sb.AppendLine(isRecurring
            ? $"    /// <summary>Registers the job <see cref=\"{typeFqn}\"/>: its executor, and a hosted service that seeds its recurring run at startup.</summary>"
            : $"    /// <summary>Registers the job <see cref=\"{typeFqn}\"/>: its executor.</summary>");
        sb.AppendLine("    /// <param name=\"builder\">The scheduling builder.</param>");
        sb.AppendLine("    /// <returns>The same builder, for chaining.</returns>");
        sb.AppendLine($"    public static global::ZeroAlloc.Scheduling.ISchedulingBuilder {diMethodName}(");
        sb.AppendLine("        this global::ZeroAlloc.Scheduling.ISchedulingBuilder builder)");
        sb.AppendLine("    {");

        if (isMediatorBridge)
        {
            sb.AppendLine($"        builder.Services.AddTransient<global::ZeroAlloc.Scheduling.IJobTypeExecutor, global::ZeroAlloc.Scheduling.Mediator.MediatorJobTypeExecutor<{typeFqn}>>();");
        }
        else
        {
            sb.AppendLine($"        builder.Services.AddTransient<global::ZeroAlloc.Scheduling.IJobTypeExecutor, {executorName}>();");
        }

        if (isRecurring)
            sb.AppendLine($"        builder.Services.AddHostedService<{startupName}>();");
        sb.AppendLine("        return builder;");
        sb.AppendLine("    }");
        sb.AppendLine("}");
    }
}
